function t($key, $vars = [])
{
    $lang = $GLOBALS['LANG'] ?? 'id';
    $txt  = $GLOBALS['TXT'] ?? [];
    $s    = $txt[$lang][$key] ?? ($txt['id'][$key] ?? $key);
    foreach ($vars as $k => $v) {
        $s = str_replace('{' . $k . '}', (string) $v, $s);
    }
    return $s;
}